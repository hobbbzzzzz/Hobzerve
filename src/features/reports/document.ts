// Turns a frozen report snapshot into a neutral document model (headings, key-values, tables).
// The PDF renderer draws this model; keeping them apart makes the content testable without parsing a PDF.

import { COMPLEXITY_LABEL, DELIVERABLE_STATUS_LABEL, PRIORITY_LABEL, STATUS_LABEL, WORK_TYPE_LABEL } from "@/lib/labels";
import type { DeliverableStatus, PriorityLevel, TaskComplexity, TaskStatus, TaskWorkType } from "@/lib/types";
import type { Json, ReportSnapshot } from "./types";

export type Align = "left" | "right";
export type Block =
  | { type: "h2"; text: string }
  | { type: "p"; text: string; tone?: "soft" | "warning" }
  | { type: "stats"; items: Array<{ label: string; value: string; hint?: string }> }
  | { type: "kv"; items: Array<{ label: string; value: string }> }
  | { type: "table"; columns: Array<{ header: string; width: number; align?: Align }>; rows: string[][]; empty?: string };

export interface ReportDocument {
  title: string;
  subtitle: string[];
  blocks: Block[];
  footer: string[];
  meta: { title: string; subject: string; generatedAt: Date };
}

const TZ = "Africa/Cairo";
const fmt = (opts: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat("en-GB", { timeZone: TZ, ...opts });
const dateTimeFmt = fmt({ weekday: "short", day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit", hour12: false });
const shortDateTimeFmt = fmt({ day: "numeric", month: "short", hour: "2-digit", minute: "2-digit", hour12: false });
const timeFmt = fmt({ hour: "2-digit", minute: "2-digit", hour12: false });
const plainDateFmt = new Intl.DateTimeFormat("en-GB", { timeZone: "UTC", weekday: "short", day: "numeric", month: "short", year: "numeric" });

export const dt = (iso?: string | null) => (iso ? dateTimeFmt.format(new Date(iso)) : "—");
export const sdt = (iso?: string | null) => (iso ? shortDateTimeFmt.format(new Date(iso)) : "—");
export const tm = (iso?: string | null) => (iso ? timeFmt.format(new Date(iso)) : "—");
export const day = (d?: string | null) => (d ? plainDateFmt.format(new Date(`${d}T12:00:00Z`)) : "—");

export function dur(seconds?: number | null, signed = false): string {
  if (seconds == null) return "—";
  const sign = seconds < 0 ? "−" : signed ? "+" : "";
  const s = Math.abs(Math.round(seconds));
  return `${sign}${Math.floor(s / 3600)}h ${String(Math.floor((s % 3600) / 60)).padStart(2, "0")}m`;
}

export function ratio(n?: number | null, d?: number | null): string {
  if (!d) return "— (none eligible)";
  return `${Math.round(((n ?? 0) / d) * 100)}%  (${n ?? 0} of ${d})`;
}

export function pct(n?: number | null, d?: number | null): string {
  return d ? `${Math.round(((n ?? 0) / d) * 100)}%` : "—";
}

const status = (s?: string) => STATUS_LABEL[s as TaskStatus] ?? s ?? "—";
const priority = (s?: string) => PRIORITY_LABEL[s as PriorityLevel] ?? s ?? "—";
const workType = (s?: string) => WORK_TYPE_LABEL[s as TaskWorkType] ?? s ?? "—";
const deliverableStatus = (s?: string) => DELIVERABLE_STATUS_LABEL[s as DeliverableStatus] ?? s ?? "—";
const list = (x: Json): Json[] => (Array.isArray(x) ? x : []);

export function footerLines(r: Pick<ReportSnapshot, "id" | "source_fingerprint" | "generated_at" | "renderer_version">): string[] {
  return [
    `SHA-256 source fingerprint: ${r.source_fingerprint}`,
    `Snapshot ${r.id} · generated ${dt(r.generated_at)} (Cairo) · renderer v${r.renderer_version}`,
  ];
}

export function buildReportDocument(r: ReportSnapshot): ReportDocument {
  const s = r.source ?? {};
  const subject = s.subject?.name ?? r.subject_name ?? "Employee";
  const subtitle = [
    [s.workspace, `${subject}${s.subject?.job_title ? ` (${s.subject.job_title})` : ""}`, "Times in Cairo time (Africa/Cairo)"].filter(Boolean).join(" · "),
    `${r.auto ? "Generated automatically after the weekly close" : `Generated by ${r.created_by_name ?? "a workspace member"}`} on ${dt(r.generated_at)}`,
  ];
  const labels = s.filter_labels ?? {};
  const filterText = Object.entries(labels)
    .map(([k, v]) => `${k.replace("_", " ")}: ${k === "work_type" ? workType(String(v)) : k === "priority" ? priority(String(v)) : k === "status" ? status(String(v)) : v}`)
    .join(", ");
  if (filterText) subtitle.push(`Filters: ${filterText}`);

  const blocks: Block[] = [];
  switch (r.kind) {
    case "daily":
      dailyBlocks(blocks, s.day ?? {});
      break;
    case "weekly":
      weeklyBlocks(blocks, s);
      break;
    case "monthly":
      kpiBlocks(blocks, s.kpis ?? {}, true);
      break;
    case "task":
      taskBlocks(blocks, s.task ?? {}, false);
      break;
    case "project":
      taskBlocks(blocks, s.task ?? {}, false);
      for (const sub of list(s.subtask_reports)) {
        blocks.push({ type: "h2", text: `Subtask · ${sub.title}` });
        taskBlocks(blocks, sub, true);
      }
      break;
  }
  blocks.push({
    type: "p",
    tone: "soft",
    text:
      "This document is rendered from a frozen snapshot. The fingerprint identifies the exact source data; if the underlying records change later, the app marks this report as changed since export.",
  });

  return { title: r.title, subtitle, blocks, footer: footerLines(r), meta: { title: r.title, subject, generatedAt: new Date(r.generated_at) } };
}

function dailyBlocks(b: Block[], d: Json) {
  const t = d.totals ?? {};
  if (d.state === "outside_membership") b.push({ type: "p", tone: "warning", text: "This day is outside the employee's membership dates, so no data is expected." });
  if (d.state === "no_recorded_work") b.push({ type: "p", text: "No recorded work on this day." });
  b.push({ type: "h2", text: "Time" });
  b.push({
    type: "stats",
    items: [
      { label: "Closed attendance", value: dur(t.closed_seconds), hint: Number(d.hours_in_day) !== 24 ? `${d.hours_in_day}-hour day (DST)` : undefined },
      { label: "On tasks", value: dur(t.task_seconds) },
      { label: "General activity", value: dur(t.general_seconds) },
      { label: "Unassigned", value: dur(t.unassigned_seconds) },
    ],
  });
  b.push({
    type: "kv",
    items: [
      { label: "Task timers and manual entries", value: dur(t.standalone_seconds) },
      { label: "…of which outside attendance (not payable)", value: dur(t.standalone_outside_attendance_seconds) },
    ],
  });
  b.push({ type: "h2", text: "Attendance sessions" });
  b.push({
    type: "table",
    columns: [
      { header: "Start", width: 0.18 },
      { header: "End", width: 0.18 },
      { header: "In this day", width: 0.16, align: "right" },
      { header: "Notes", width: 0.48 },
    ],
    rows: list(d.sessions).map((x) => [
      sdt(x.started_at),
      sdt(x.ended_at),
      dur(x.seconds),
      [x.origin === "manual" ? "Added later" : "", x.corrected ? "Corrected" : "", x.summary ?? ""].filter(Boolean).join(" · "),
    ]),
    empty: "No closed attendance sessions.",
  });
  b.push({ type: "h2", text: "Activity timeline" });
  b.push({
    type: "table",
    columns: [
      { header: "From", width: 0.12 },
      { header: "To", width: 0.12 },
      { header: "Activity", width: 0.6 },
      { header: "Duration", width: 0.16, align: "right" },
    ],
    rows: list(d.segments).map((x) => [
      tm(x.from),
      tm(x.to),
      x.kind === "task" ? `${x.parent ? `${x.parent} › ` : ""}${x.task ?? "Task"}` : x.kind === "general" ? x.general_type : "Unassigned",
      dur(x.seconds),
    ]),
    empty: "No recorded activity.",
  });
  b.push({ type: "h2", text: "Tasks worked on" });
  b.push({
    type: "table",
    columns: [
      { header: "Task", width: 0.44 },
      { header: "Time", width: 0.14, align: "right" },
      { header: "Progress", width: 0.2 },
      { header: "Completed", width: 0.22 },
    ],
    rows: list(d.tasks).map((x) => [
      `${x.parent ? `${x.parent} › ` : ""}${x.title}`,
      dur(x.seconds),
      list(x.progress).map((p) => `${p.from ?? 0}% → ${p.to}%`).join(", ") || "—",
      list(x.completions).map((c) => `${tm(c.at)}${c.first ? " (first)" : ""}`).join(", ") || "—",
    ]),
    empty: "No tasks worked on.",
  });
  if (list(d.events).length) {
    b.push({ type: "h2", text: "Other recorded events" });
    b.push({
      type: "table",
      columns: [
        { header: "Time", width: 0.12 },
        { header: "Event", width: 0.88 },
      ],
      rows: list(d.events).map((e) => [tm(e.at), `${e.summary}${e.body ? ` — “${e.body}”` : ""}`]),
    });
  }
  if (list(d.due).length) {
    b.push({ type: "h2", text: "Deadlines on this day" });
    b.push({
      type: "table",
      columns: [
        { header: "Task", width: 0.6 },
        { header: "Due", width: 0.15 },
        { header: "Status", width: 0.25 },
      ],
      rows: list(d.due).map((x) => [x.title, tm(x.due_at), status(x.status)]),
    });
  }
}

function weeklyBlocks(b: Block[], s: Json) {
  const w = s.week ?? {};
  b.push({ type: "h2", text: "Hours" });
  b.push({
    type: "stats",
    items: [
      { label: "Target", value: dur(w.target_seconds), hint: `${w.active_working_days ?? "?"} working day(s)` },
      { label: w.closed ? "Closed attendance (frozen)" : "Closed attendance", value: dur(w.closed_seconds) },
      { label: "Regular", value: dur(w.regular_seconds) },
      { label: "Overtime", value: dur(w.overtime_seconds), hint: `Payroll month ${w.payroll_month ?? "—"}` },
    ],
  });
  b.push({
    type: "kv",
    items: [
      { label: "Week status", value: w.closed ? `Closed ${dt(w.closure?.closed_at)}` : "Not closed yet — figures are provisional" },
      { label: "Net after adjustments posted into this week", value: `${dur(w.net_regular_seconds)} regular + ${dur(w.net_overtime_seconds)} overtime` },
      ...(w.closed && w.current_closed_seconds !== w.closed_seconds
        ? [{ label: "Attendance recorded for this week now", value: `${dur(w.current_closed_seconds)} (the closed figure does not change)` }]
        : []),
    ],
  });
  b.push({
    type: "table",
    columns: [
      { header: "Day", width: 0.5 },
      { header: "Closed attendance", width: 0.25, align: "right" },
      { header: "Tasks worked on", width: 0.25, align: "right" },
    ],
    rows: list(s.days).map((x) => [day(x.date), dur(x.closed_seconds), String(x.worked_count)]),
  });
  adjustmentBlocks(b, list(w.adjustments_in), list(w.adjustments_out));
  kpiBlocks(b, s.kpis ?? {}, false);
}

function adjustmentBlocks(b: Block[], incoming: Json[], outgoing: Json[]) {
  if (!incoming.length && !outgoing.length) return;
  b.push({ type: "h2", text: "Adjustments" });
  if (incoming.length)
    b.push({
      type: "table",
      columns: [
        { header: "Posted here from week of", width: 0.4 },
        { header: "Regular", width: 0.3, align: "right" },
        { header: "Overtime", width: 0.3, align: "right" },
      ],
      rows: incoming.map((a) => [day(a.source_week_start), dur(a.regular_delta_seconds, true), dur(a.overtime_delta_seconds, true)]),
    });
  if (outgoing.length)
    b.push({
      type: "table",
      columns: [
        { header: "Correction to this week, posted to week of", width: 0.4 },
        { header: "Regular", width: 0.3, align: "right" },
        { header: "Overtime", width: 0.3, align: "right" },
      ],
      rows: outgoing.map((a) => [day(a.posted_week_start), dur(a.regular_delta_seconds, true), dur(a.overtime_delta_seconds, true)]),
    });
}

function kpiBlocks(b: Block[], k: Json, monthly: boolean) {
  const at = k.on_time_at_completion ?? {};
  const re = k.on_time_restated ?? {};
  b.push({ type: "h2", text: "Work" });
  b.push({
    type: "stats",
    items: [
      { label: "Completed", value: String(k.throughput?.value ?? 0), hint: `First completions · ${k.throughput?.subtasks ?? 0} subtasks apart` },
      { label: "Worked on", value: String(k.worked_on?.value ?? 0), hint: `${k.worked_on?.subtasks ?? 0} subtasks apart` },
      { label: "On time at completion", value: pct(at.numerator, at.denominator), hint: at.denominator ? `${at.numerator} of ${at.denominator}` : "None with a deadline" },
      { label: "On time (restated)", value: pct(re.numerator, re.denominator), hint: re.denominator ? `${re.numerator} of ${re.denominator}` : "None with a deadline" },
    ],
  });
  b.push({
    type: "kv",
    items: [
      { label: "Due-task completion", value: `${ratio(k.due_completion?.numerator, k.due_completion?.denominator)} · ${k.due_completion?.not_yet_due ?? 0} not yet due · ${k.due_completion?.cancelled ?? 0} cancelled` },
      { label: "Expected deliverables fulfilled", value: ratio(k.deliverable_fulfillment?.numerator, k.deliverable_fulfillment?.denominator) },
      { label: "Own-initiative tasks", value: `${k.proactive?.created ?? 0} created, ${k.proactive?.completed ?? 0} completed` },
      { label: "Extra deliverables", value: `${k.extras?.self_initiated ?? 0} self-initiated, ${k.extras?.manager_requested ?? 0} manager-requested` },
      { label: "Reopened", value: `${k.reopens?.revision ?? 0} revision, ${k.reopens?.additional_scope ?? 0} additional scope` },
      { label: "Deadline changes", value: String(k.deadline_changes?.count ?? 0) },
      { label: "Unassigned attendance", value: dur(k.attendance?.unassigned_seconds) },
    ],
  });
  b.push({ type: "p", tone: "soft", text: "These are separate measures. Hobzerve never combines them into a single performance score." });

  if (monthly) {
    b.push({ type: "h2", text: "Hours by week (each week counts in the month of its Friday)" });
    b.push({
      type: "table",
      columns: [
        { header: "Week of", width: 0.2 },
        { header: "Target", width: 0.11, align: "right" },
        { header: "Closed", width: 0.11, align: "right" },
        { header: "Regular", width: 0.11, align: "right" },
        { header: "Overtime", width: 0.11, align: "right" },
        { header: "Adjustments (reg / OT)", width: 0.24, align: "right" },
        { header: "Net OT", width: 0.12, align: "right" },
      ],
      rows: list(k.attendance?.weeks).map((w) => [
        `${day(w.week_start)}${w.closed ? "" : " *"}`,
        dur(w.target_seconds),
        dur(w.closed_seconds),
        dur(w.regular_seconds),
        dur(w.overtime_seconds),
        w.adjustment_regular_seconds || w.adjustment_overtime_seconds
          ? `${dur(w.adjustment_regular_seconds, true)} / ${dur(w.adjustment_overtime_seconds, true)}`
          : "—",
        dur(w.net_overtime_seconds),
      ]),
      empty: "No weeks end in this month.",
    });
    b.push({
      type: "kv",
      items: [
        { label: "Total overtime for the month", value: `${dur(k.attendance?.overtime_seconds)}${k.attendance?.final ? "" : " (provisional — * week not closed yet)"}` },
        { label: "Closed attendance in the month", value: dur(k.attendance?.closed_seconds) },
      ],
    });
    b.push({ type: "h2", text: "By category" });
    b.push({
      type: "table",
      columns: [
        { header: "Category", width: 0.32 },
        { header: "Completed", width: 0.14, align: "right" },
        { header: "Worked on", width: 0.14, align: "right" },
        { header: "Avg calendar days", width: 0.2, align: "right" },
        { header: "Tracked hours", width: 0.2, align: "right" },
      ],
      rows: list(k.by_category).map((c) => [c.name, String(c.throughput), String(c.worked_on), c.avg_calendar_days == null ? "—" : String(c.avg_calendar_days), dur(c.tracked_seconds)]),
      empty: "No activity.",
    });
    b.push({ type: "h2", text: "By work type" });
    b.push({
      type: "table",
      columns: [
        { header: "Work type", width: 0.32 },
        { header: "Completed", width: 0.14, align: "right" },
        { header: "Worked on", width: 0.14, align: "right" },
        { header: "Avg calendar days", width: 0.2, align: "right" },
        { header: "Tracked hours", width: 0.2, align: "right" },
      ],
      rows: list(k.by_work_type).map((c) => [workType(c.work_type), String(c.throughput), String(c.worked_on), c.avg_calendar_days == null ? "—" : String(c.avg_calendar_days), dur(c.tracked_seconds)]),
      empty: "No activity.",
    });
  }

  b.push({ type: "h2", text: "Completed tasks" });
  b.push({
    type: "table",
    columns: [
      { header: "Task", width: 0.42 },
      { header: "First completed", width: 0.2 },
      { header: "Category", width: 0.14 },
      { header: "Calendar days", width: 0.12, align: "right" },
      { header: "Tracked", width: 0.12, align: "right" },
    ],
    rows: list(k.throughput?.items).map((t) => [t.title, sdt(t.completed_at), t.category ?? "—", String(t.calendar_days ?? "—"), dur(t.effort_seconds)]),
    empty: "No tasks completed in this period.",
  });
  const div = list(re.diverging);
  if (div.length) {
    b.push({ type: "h2", text: "On time at completion vs restated" });
    b.push({
      type: "table",
      columns: [
        { header: "Task", width: 0.3 },
        { header: "Completed", width: 0.16 },
        { header: "Due then", width: 0.16 },
        { header: "Due now", width: 0.16 },
        { header: "Deadline changes after completion", width: 0.22 },
      ],
      rows: div.map((t) => [
        t.title,
        sdt(t.completed_at),
        sdt(t.due_at_completion),
        sdt(t.due_at_latest),
        list(t.changes).map((c) => `${c.reason} (${c.by})`).join("; ") || "—",
      ]),
    });
  }
  b.push({ type: "h2", text: "Worked on" });
  b.push({
    type: "table",
    columns: [
      { header: "Task", width: 0.75 },
      { header: "Category", width: 0.25 },
    ],
    rows: list(k.worked_on?.items).map((t) => [t.title, t.category ?? "—"]),
    empty: "No tasks worked on.",
  });
  if (list(k.deadline_changes?.items).length) {
    b.push({ type: "h2", text: "Deadline changes" });
    b.push({
      type: "table",
      columns: [
        { header: "Task", width: 0.26 },
        { header: "From → to", width: 0.28 },
        { header: "Reason", width: 0.3 },
        { header: "By", width: 0.16 },
      ],
      rows: list(k.deadline_changes.items).map((c) => [c.task, `${sdt(c.from)} → ${sdt(c.to)}`, c.reason, c.by]),
    });
  }
}

function taskBlocks(b: Block[], t: Json, compact: boolean) {
  b.push({
    type: "kv",
    items: [
      ...(compact ? [] : [{ label: "Task", value: t.title }]),
      ...(t.parent ? [{ label: "Part of", value: t.parent.title }] : []),
      { label: "Status", value: `${status(t.status)} · ${t.progress ?? 0}% progress${t.archived ? " · archived" : ""}` },
      { label: "Assigned to", value: t.assignee },
      { label: "Created by", value: `${t.creator} on ${dt(t.created_at)}` },
      { label: "Category · type · complexity", value: `${t.category ?? "—"} · ${workType(t.work_type)} · ${COMPLEXITY_LABEL[t.complexity as TaskComplexity] ?? "—"}` },
      { label: "Priority", value: priority(t.priority_level) },
      { label: "Deadline", value: `${dt(t.current_due_at)}${t.original_due_at && t.original_due_at !== t.current_due_at ? ` (originally ${dt(t.original_due_at)})` : ""}` },
      { label: "Started · first completed", value: `${dt(t.started_at)} · ${dt(t.first_completed_at)}` },
      { label: "Tracked time", value: `${dur(t.effort_seconds)} including subtasks · ${dur(t.direct_effort_seconds)} directly${t.estimated_minutes ? ` · estimate ${dur(t.estimated_minutes * 60)}` : ""}` },
    ],
  });
  if (!compact && t.description) b.push({ type: "p", text: t.description });

  if (list(t.deadline_changes).length) {
    b.push({ type: "h2", text: compact ? "Deadline changes" : "Deadline history" });
    b.push({
      type: "table",
      columns: [
        { header: "Changed", width: 0.18 },
        { header: "From → to", width: 0.32 },
        { header: "Reason", width: 0.34 },
        { header: "By", width: 0.16 },
      ],
      rows: list(t.deadline_changes).map((c) => [sdt(c.at), `${sdt(c.from)} → ${sdt(c.to)}`, c.reason, c.by]),
    });
  }
  if (list(t.completions).length) {
    b.push({ type: "h2", text: "Completions" });
    b.push({
      type: "table",
      columns: [
        { header: "Completed", width: 0.2 },
        { header: "Kind", width: 0.16 },
        { header: "On time then", width: 0.14 },
        { header: "Gaps documented", width: 0.5 },
      ],
      rows: list(t.completions).map((c) => [
        sdt(c.at),
        c.first ? "First" : "Re-completion",
        c.on_time == null ? "No deadline" : c.on_time ? "Yes" : "No",
        [...list(c.missing).map((m) => `${m.title}: ${m.reason}`), ...list(c.unfinished_subtasks).map((m) => `Subtask ${m.title}: ${m.reason}`)].join("; ") || "—",
      ]),
    });
  }
  if (list(t.deliverables).length) {
    b.push({ type: "h2", text: "Deliverables" });
    b.push({
      type: "table",
      columns: [
        { header: "Deliverable", width: 0.36 },
        { header: "Type", width: 0.2 },
        { header: "Status", width: 0.16 },
        { header: "Cycle", width: 0.08, align: "right" },
        { header: "Evidence", width: 0.2 },
      ],
      rows: list(t.deliverables).map((d) => [
        `${d.title}${d.archived ? " (archived)" : ""}`,
        d.kind === "extra" ? (d.origin === "self_initiated" ? "Extra · self-initiated" : "Extra · manager-requested") : "Expected",
        deliverableStatus(d.status),
        String(d.cycle ?? ""),
        list(d.evidence).map((e) => e.url ?? e.note).join("; ") || "—",
      ]),
    });
  }
  if (list(t.scope_cycles).length > 1 || list(t.revision_rounds).length) {
    b.push({ type: "h2", text: "Scope cycles and revisions" });
    b.push({
      type: "table",
      columns: [
        { header: "What", width: 0.3 },
        { header: "Opened", width: 0.2 },
        { header: "Reason", width: 0.5 },
      ],
      rows: [
        ...list(t.scope_cycles).map((c) => [`Scope cycle ${c.sequence} (${c.type})`, sdt(c.opened_at), c.reason ?? "—"]),
        ...list(t.revision_rounds).map((r) => [`Revision round ${r.sequence}`, sdt(r.opened_at), r.reason]),
      ],
    });
  }
  if (list(t.subtasks).length) {
    b.push({ type: "h2", text: "Subtasks" });
    b.push({
      type: "table",
      columns: [
        { header: "Subtask", width: 0.4 },
        { header: "Status", width: 0.16 },
        { header: "Progress", width: 0.12, align: "right" },
        { header: "Due", width: 0.18 },
        { header: "Tracked", width: 0.14, align: "right" },
      ],
      rows: list(t.subtasks).map((x) => [x.title, status(x.status), `${x.progress}%`, sdt(x.due_at), dur(x.effort_seconds)]),
    });
  }
  if (!compact && list(t.history).length) {
    b.push({ type: "h2", text: "History" });
    b.push({
      type: "table",
      columns: [
        { header: "When", width: 0.18 },
        { header: "What happened", width: 0.82 },
      ],
      rows: list(t.history).map((h) => [sdt(h.at), `${h.summary}${h.body ? ` — “${h.body}”` : ""}`]),
    });
  }
}
